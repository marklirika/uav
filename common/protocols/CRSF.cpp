uint8_t crc8(const uint8_t *ptr, uint8_t len) {
    uint8_t crc = 0;
    for (uint8_t i = 0; i < len; i++)
    {
        crc = crc8tab[crc ^ *ptr++];
    }
    return crc;
}

uint8_t CRSF::computeCRC(const uint8_t *data, size_t lenght) {
    uint8_t crc = 0;
    for (uint8_t i = 0; i < lenght; i++)
    {
        crc = crc8tab[crc ^ *data++];
    }
    return crc;
}

CRSF::CRSF() {
    channels.fill(1500);
    /* Trottle initial value? */
    channels[THROTTLE_INDEX] = 880;
}

void CRSF::set(RotPacket packet) {
    
    if (packet.header != static_cast<int>(Protocol::CRSF)) {
        throw std::runtime_error("Wrong protocol type received in rot packet, can not safely convert to CRSF");
    }

    channels[THROTTLE_INDEX] = packet.throttle;
    channels[YAW_INDEX] = packet.yaw;
    channels[PITCH_INDEX] = packet.pitch;
    channels[ROLL_INDEX] = packet.roll;
    channels[ARM_INDEX] = packet.arm;
}
const std::array<uint8_t, CRSF_SIZE> CRSF::unpack() {
    std::array<uint8_t, CRSF_SIZE> packet;

    packet[0] = CRSF_TX_ADDR;
    packet[1] = CRSF_PAYLOAD_SIZE;
    packet[2] = CRSF_RC_PACKET;

    /* 880 2160 - perfect values */
    constexpr uint16_t min_16bit = 880;
    constexpr uint16_t max_16bit = 2160;

    std::array<uint16_t, 16> scaled_channels;
    for (size_t i = 0; i < channels.size(); ++i) {
        scaled_channels[i] = static_cast<uint16_t>(
            static_cast<float>(channels[i] - min_16bit) / (max_16bit - min_16bit) * 2047.0f
        );
    }

    packet[3] = scaled_channels[0] & 0xFF;
    packet[4] = (((scaled_channels[0] & 0x07FF) >> 8) | ((scaled_channels[1] & 0x07FF) << 3) & 0xFF);
    packet[5] = (((scaled_channels[1] & 0x07FF) >> 5) | ((scaled_channels[2] & 0x07FF) << 6) & 0xFF);
    packet[6] = ((scaled_channels[2] & 0x07FF) >> 2) & 0xFF;
    packet[7] = (((scaled_channels[2] & 0x07FF) >> 10) | ((scaled_channels[3] & 0x07FF) << 1) & 0xFF);
    packet[8] = (((scaled_channels[3] & 0x07FF) >> 7) | ((scaled_channels[4] & 0x07FF) << 4) & 0xFF);
    packet[9] = (((scaled_channels[4] & 0x07FF) >> 4) | ((scaled_channels[5] & 0x07FF) << 7) & 0xFF);
    packet[10] = ((scaled_channels[5] & 0x07FF) >> 1) & 0xFF;
    packet[11] = (((scaled_channels[5] & 0x07FF) >> 9) | ((scaled_channels[6] & 0x07FF) << 2) & 0xFF);
    packet[12] = (((scaled_channels[6] & 0x07FF) >> 6) | ((scaled_channels[7] & 0x07FF) << 5) & 0xFF);
    packet[13] = ((scaled_channels[7] & 0x07FF) >> 3) & 0xFF;
    packet[14] = scaled_channels[8] & 0xFF;
    packet[15] = (((scaled_channels[8] & 0x07FF) >> 8) | ((scaled_channels[9] & 0x07FF) << 3) & 0xFF);
    packet[16] = (((scaled_channels[9] & 0x07FF) >> 5) | ((scaled_channels[10] & 0x07FF) << 6) & 0xFF);
    packet[17] = ((scaled_channels[10] & 0x07FF) >> 2) & 0xFF;
    packet[18] = (((scaled_channels[10] & 0x07FF) >> 10) | ((scaled_channels[11] & 0x07FF) << 1) & 0xFF);
    packet[19] = (((scaled_channels[11] & 0x07FF) >> 7) | ((scaled_channels[12] & 0x07FF) << 4) & 0xFF);
    packet[20] = (((scaled_channels[12] & 0x07FF) >> 4) | ((scaled_channels[13] & 0x07FF) << 7) & 0xFF);
    packet[21] = ((scaled_channels[13] & 0x07FF) >> 1) & 0xFF;
    packet[22] = (((scaled_channels[13] & 0x07FF) >> 9) | ((scaled_channels[14] & 0x07FF) << 2) & 0xFF);
    packet[23] = (((scaled_channels[14] & 0x07FF) >> 6) | ((scaled_channels[15] & 0x07FF) << 5) & 0xFF);
    packet[24] = ((scaled_channels[15] & 0x07FF) >> 3) & 0xFF;

    packet[25] = computeCRC(&packet[2], CRSF_PAYLOAD_SIZE - 1);

    return packet;
}

